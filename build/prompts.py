def rendered(p, kind="read"):
    """Готовый текст промпта — ровно то, что участник копирует со страницы."""
    if kind == "check":
        return ASK_CHECK.format(story=p["story"], schema=p["schema"])
    if kind == "code":
        return ASK_CODE.format(method=p["method"], schema=p["schema"])
    if kind == "html":
        return ASK_HTML.format(js=p["js"], fields=p["fields"], nrows=p["nrows"],
                               algo=p["algo"], kpi=p["kpi"], chart=p["chart"],
                               charts=p["charts"], table=p["table"],
                               title=p["title"], sample=_sample(p["csv"]))
    if kind == "naive":
        return p["naive"].format(raw=p["raw"]())
    if kind == "read":
        return ASK_READ.format(story=p["story"], results=p["results"],
                               frame=FRAME.format(ask=p["ask"]))
    raise ValueError(kind)


