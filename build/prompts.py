    return ("выдачи ипотеки, млрд ₽ в месяц:\nигрок | было год назад | стало сейчас\n" +
            "\n".join(f"{x['bank']} | {_n(float(x['was_bn_rub']))} | {_n(float(x['now_bn_rub']))}"
                      for x in r))


