import pathlib

DATA = pathlib.Path(__file__).resolve().parent.parent / "data"
RU = {1: "янв", 2: "фев", 3: "мар", 4: "апр", 5: "май", 6: "июн",
      7: "июл", 8: "авг", 9: "сен", 10: "окт", 11: "ноя", 12: "дек"}


def _rows(name):
    with (DATA / name).open(encoding="utf-8") as f:
        return list(csv.DictReader(f))


def _n(x, k=1):
    return f"{x:.{k}f}".replace(".", ",")


# ── что участник видит «как есть» (нужно промпту-ловушке) ───────────────────

def raw_tat():
    r = _rows("loan_tat_90d.csv")
    return "\n".join("  ".join(
        f"{dt.date.fromisoformat(x['date']).strftime('%d.%m')} {_n(float(x['tat_min']))}"
        for x in r[i:i + 6]) for i in range(0, len(r), 6))


def raw_ops():
    r = _rows("weekly_ops_26w.csv")
    return ("неделя | обращения, тыс. | отток по картам, % | доля сессий с ошибкой, %\n" +
            "\n".join(f"{dt.date.fromisoformat(x['week_start']).strftime('%d.%m')} | "
                      f"{_n(float(x['calls_th']))} | {_n(float(x['churn_pct']), 2)} | "
                      f"{_n(float(x['app_error_rate_pct']), 2)}" for x in r))


def raw_issues():
    r = _rows("issues_daily_3y.csv")
    tot = {}
    for x in r:
        d = dt.date.fromisoformat(x["date"])
        tot[(d.year, d.month)] = tot.get((d.year, d.month), 0) + float(x["amount_mln_rub"])
    return ("выдачи потребкредитов по месяцам, млн ₽:\nгод | " +
            " | ".join(RU[m] for m in range(1, 13)) + "\n" +
            "\n".join(str(y) + " | " + " | ".join(f"{tot[(y, m)]:.0f}" for m in range(1, 13))
                      for y in (2023, 2024, 2025)))


def raw_mortgage():
    r = _rows("mortgage_market.csv")
    return ("выдачи ипотеки, млрд ₽ в месяц:\nигрок | было год назад | стало сейчас\n" +
            "\n".join(f"{x['bank']} | {_n(float(x['was_bn_rub']))} | {_n(float(x['now_bn_rub']))}"
                      for x in r))


def raw_msb():
    return ("средний срок рассмотрения заявки МСБ за квартал — 2,1 дня при нормативе 3 дня, "
            "всего 18 400 заявок")


