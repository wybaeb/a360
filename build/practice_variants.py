"""Варианты практического занятия: три направления × три варианта.

Каждый вариант описывает проект по каркасу (проблема → метрика → данные →
инструмент → анализ → вывод → эффект), дерево из двух этажей — итоговая
метрика эффекта и три входа, — и для каждого входа два источника данных
с разной скоростью и ценой получения. У каждого источника свой CSV-файл:
что выбрано в дереве, то и загружается в мини-инструмент. Формула расчёта
привязана к источнику; из выбранных источников собирается промпт.

Виды источников (kind):
  monthly — свёртка по месяцам, столбец значения готов (быстро, бесплатно);
  detail  — детальная выгрузка по срезам, нужна свёртка (дольше, дороже);
  params  — параметры из финансовой модели продукта (таблица параметр;значение);
  rates   — тарифная сетка по месяцам, значение считается из двух ставок;
  share_m — доля из витрины по месяцам: числитель и знаменатель столбцами;
  survey  — опрос или выборочная сверка: доля строк с нужным признаком.

Файлы данных пишутся в a360/practice_data/<вариант>/; описание вариантов —
в build/src/practice_variants.json для страницы тренажёра и прогона.
Все выгрузки синтетические; числа вариантов, совпадающих с кейсами курса,
согласованы с finmodel_core.ПРЕСЕТЫ.
"""
