ВЕСА_К = [4, 3, 2, 1]


def _w(path, cols, rows):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f, delimiter=";")
        w.writerow(cols)
        for r in rows:
            w.writerow([str(x).replace(".", ",") if isinstance(x, float) else x for x in r])


def ряд(rnd, start, end, noise=0.04):
    return [(start + (end - start) * i / 23) * (1 + rnd.uniform(-noise, noise)) for i in range(24)]


def split(rnd, total, weights):
    s = sum(weights)
    parts = [total * w / s * (1 + rnd.uniform(-0.15, 0.15)) for w in weights]
    k = total / sum(parts)
    return [p * k for p in parts]


