def _params_src(id_, name, days, cost, file, params, calc, expect, js=None):
    if js is None:
        js = calc
        for имя, _ in params:
            js = js.replace(имя, f"p['{имя}']")
        js = js.replace("×", "*").replace("÷", "/").replace("−", "-")
    return Ист(id_, name, days, cost, file, "params", params=params, calc=calc, expect=expect, js=js)


