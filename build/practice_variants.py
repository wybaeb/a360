class Ист:
    """Описание источника и запись его файла. expect считается из данных."""

    def __init__(self, id_, name, days, cost, file, kind, **kw):
        self.id, self.name, self.days, self.cost, self.file, self.kind, self.kw = id_, name, days, cost, file, kind, kw

    def ref(self):
        """Контрольный расчёт входа на JS: function (rows) → число; rows — строки файла."""
        k = self.kw
        if self.kind == "monthly":
            n = k.get("last", 12)
            agg = "s / last.length" if k.get("agg", "mean") == "mean" else "s"
            return (f"var last = rows.slice(-{n}), s = 0; for (var i = 0; i < last.length; i++) s += last[i]['{k['col']}']; return {agg};")
        if self.kind == "detail":
            n = k.get("last", 12)
            return (f"var by = {{}}, order = []; for (var i = 0; i < rows.length; i++) {{ var m = rows[i]['месяц']; if (by[m] === undefined) {{ by[m] = 0; order.push(m); }} by[m] += rows[i]['{k['col']}']; }}"
                    f" var last = order.slice(-{n}), s = 0; for (var j = 0; j < last.length; j++) s += by[last[j]]; return s / last.length;")
        if self.kind == "params":
            return f"var p = {{}}; for (var i = 0; i < rows.length; i++) p[rows[i]['параметр']] = rows[i]['значение']; return {k['js']};"
        if self.kind == "rates":
            return f"var s = 0; for (var i = 0; i < rows.length; i++) {{ var r = rows[i]; s += ({k['js']}); }} return s / rows.length;"
        if self.kind == "share_m":
            return f"var n = 0, d = 0; for (var i = 0; i < rows.length; i++) {{ n += rows[i]['{k['num_col']}']; d += rows[i]['{k['den_col']}']; }} return d ? n / d : null;"
        if self.kind == "survey":
            return f"var c = 0; for (var i = 0; i < rows.length; i++) if (rows[i]['{k['col']}'] === '{k['yes']}') c++; return rows.length ? c / rows.length : null;"
        raise ValueError(self.kind)

    def write(self, rnd, d, inp):
        k = self.kw
        if self.kind == "monthly":
            # value: ряд; extra: {col: ряд}
            cols = ["месяц", k["col"]] + list(k.get("extra", {}).keys())
            rows = [[m, k["fmt"](k["value"][i])] + [k["fmt"](v[i]) for v in k.get("extra", {}).values()] for i, m in enumerate(МЕСЯЦЫ)]
            _w(d / self.file, cols, rows)
            n = k.get("last", 12)
            exp = sum(k["value"][-n:]) / n
            calc = (f"среднее значение столбца {k['col']} за последние {n} строк (месяцев)" if k.get("agg", "mean") == "mean"
                    else f"сумма столбца {k['col']} за последние {n} строк (месяцев)")
            if k.get("agg") == "sum":
                exp = sum(k["value"][-n:])
            return calc, exp
        if self.kind == "detail":
            slices, weights, sl_col = k.get("slices", РЕГИОНЫ), k.get("weights", ВЕСА_Р), k.get("slice_col", "регион")
            rows = []
            for i, m in enumerate(МЕСЯЦЫ):
                for s, v in zip(slices, split(rnd, k["value"][i], weights)):
                    rows.append([m, s, k["fmt"](v)])
            _w(d / self.file, ["месяц", sl_col, k["col"]], rows)
            n = k.get("last", 12)
            exp = sum(k["value"][-n:]) / n
            return (f"сложить {k['col']} по строкам одного месяца (строк на месяц несколько — по одной на каждый {sl_col}), "
                    f"затем среднее по последним {n} месяцам"), exp
        if self.kind == "params":
            _w(d / self.file, ["параметр", "значение"], [[p, v] for p, v in k["params"]])
            return k["calc"], k["expect"]
        if self.kind == "rates":
            a, b = k["a"], k["b"]
            rows = [[m, round(a[i], 2), round(b[i], 2)] for i, m in enumerate(МЕСЯЦЫ)]
            _w(d / self.file, ["месяц", k["col_a"], k["col_b"]], rows)
            return k["calc"], k["expect"]
        if self.kind == "share_m":
            num, den = k["num"], k["den"]
            rows = [[m, round(den[i]), round(num[i])] for i, m in enumerate(МЕСЯЦЫ)]
            _w(d / self.file, ["месяц", k["den_col"], k["num_col"]], rows)
            exp = sum(num) / sum(den)
            return f"сумма столбца {k['num_col']} ÷ сумма столбца {k['den_col']} по всем строкам", exp
        if self.kind == "survey":
            n, share, col, yes, others = k["n"], k["share"], k["col"], k["yes"], k["others"]
            vals = [yes] * round(n * share)
            rest = n - len(vals)
            for j in range(rest):
                vals.append(others[j % len(others)])
            rnd.shuffle(vals)
            _w(d / self.file, [k.get("id_col", "id"), col], [[k.get("id0", 100000) + i, v] for i, v in enumerate(vals)])
            return f"доля строк, где {col} равно «{yes}»", len([v for v in vals if v == yes]) / n
        raise ValueError(self.kind)


def вход(id_, name, unit, a, b):
    return dict(id=id_, name=name, unit=unit, sources=[a, b])


def собрать(rnd, v):
    """Записать файлы источников варианта и вернуть описание для JSON."""
    d = DATA / v["id"]
    inputs = []
    for inp in v["inputs"]:
        srcs = []
        for s in inp["sources"]:
            s.file = f"{inp['id']}_{s.id}.csv"      # латинские имена: модель воспроизводит их точно
            calc, exp = s.write(rnd, d, inp)
            srcs.append(dict(id=s.id, name=s.name, days=s.days, cost=s.cost, file=s.file, kind=s.kind,
                             calc=calc, ref=s.ref(), expect=round(exp, 4 if abs(exp) < 10 else 2 if abs(exp) < 1000 else 0)))
        inputs.append(dict(id=inp["id"], name=inp["name"], unit=inp["unit"], sources=srcs))
    out = dict(v); out["inputs"] = inputs
    return out


