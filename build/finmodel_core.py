# -*- coding: utf-8 -*-
"""Модель эффекта проекта — один расчёт для страницы «Финансовая модель
проекта», тренажёра «Финансовая модель эффекта» (там же на JS, формулы
идентичны) и тетради практики.

Эффект в месяц по формуле «изменение показателя × объём × стоимость единицы»
разворачивается во времени: выход на полный уровень за T месяцев, срок
сохранения R месяцев, затраты — единовременные C0 и ежемесячные c.
Два типа эффекта:

  * «когорты» — единицы эффекта (удержанные счета, активированные карты)
    появляются каждый месяц и приносят доход P в месяц каждая в течение
    R месяцев; поток нарастает по мере накопления когорт;
  * «уровень» — эффект действует как постоянный поток Δ·V·P в месяц
    в течение R месяцев после выхода на уровень.

Дисконтирование помесячное по годовой ставке r: m = (1+r)^(1/12) − 1.
"""
import math

NBSP = " "


def fmt(n, dec=0):
    """Число с узкими неразрывными пробелами между тысячами и запятой."""
    s = f"{n:,.{dec}f}".replace(",", NBSP).replace(".", ",")
    return s


def млн(n, dec=1):
    return fmt(n / 1e6, dec) + " млн руб."


def тыс(n, dec=0):
    return fmt(n / 1e3, dec) + " тыс. руб."


def ramp(t, T):
    """Доля полного уровня в месяце t (1 — первый месяц эффекта)."""
    if T <= 0:
        return 1.0
    return min(t / T, 1.0)


def потоки(p):
    """Помесячные потоки: месяц 0 — только единовременные затраты.

    p: delta, volume, price (руб. на единицу в месяц), ramp (T, мес),
       keep (R, мес), capex, opex, horizon (H, мес), rate (годовая, доля),
       kind ('cohort' | 'level').
    Возвращает список словарей по месяцам 0..H с полями
    units, income, cost, cf, cum, disc, cum_disc.
    """
    H = int(p["horizon"])
    T, R = p["ramp"], p["keep"]
    full = p["delta"] * p["volume"]
    m = (1 + p["rate"]) ** (1 / 12) - 1
    rows = []
    cum = cum_d = 0.0
    for t in range(0, H + 1):
        if t == 0:
            income, units, cost = 0.0, 0.0, p["capex"]
        else:
            cost = p["opex"]
            if p["kind"] == "cohort":
                # когорты k = 1..t, живут R месяцев: k > t − R
                units = sum(full * ramp(k, T) for k in range(max(1, t - R + 1), t + 1))
            else:
                units = full * ramp(t, T) if t <= R else 0.0
            income = units * p["price"]
        cf = income - cost
        cum += cf
        disc = cf / (1 + m) ** t
        cum_d += disc
        rows.append(dict(t=t, units=units, income=income, cost=cost, cf=cf,
                         cum=cum, disc=disc, cum_disc=cum_d))
    return rows


def итоги(p):
    rows = потоки(p)
    H = int(p["horizon"])
    payback = next((r["t"] for r in rows if r["t"] > 0 and r["cum"] >= 0), None)
    payback_d = next((r["t"] for r in rows if r["t"] > 0 and r["cum_disc"] >= 0), None)
    year1 = sum(r["income"] for r in rows if 1 <= r["t"] <= 12)
    full_month = p["delta"] * p["volume"] * p["price"]
    return dict(rows=rows, npv=rows[-1]["cum_disc"], cum=rows[-1]["cum"],
                payback=payback, payback_disc=payback_d, year1=year1,
                full_month=full_month, horizon=H,
                income=sum(r["income"] for r in rows),
                cost=sum(r["cost"] for r in rows))


def чувствительность(p, допущения):
    """Каждое допущение по очереди в пессимистичное значение.

    допущения: список (ключ, название, базовое, пессимистичное, оптимистичное).
    Возвращает строки с NPV при пессимистичном и оптимистичном значении
    и признаком «вывод меняется» (знак NPV).
    """
    база = итоги(p)["npv"]
    out = []
    for ключ, имя, б, пес, опт in допущения:
        q = dict(p); q[ключ] = пес
        npv_p = итоги(q)["npv"]
        q = dict(p); q[ключ] = опт
        npv_o = итоги(q)["npv"]
        out.append(dict(key=ключ, name=имя, base=б, pess=пес, opt=опт,
                        npv_pess=npv_p, npv_opt=npv_o,
                        flips=(npv_p < 0) != (база < 0),
                        span=abs(npv_o - npv_p)))
    out.sort(key=lambda r: -r["span"])
    return out


