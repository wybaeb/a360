        группа_подпись="ИНСТРУМЕНТЫ API",
        инструменты=[("create_dashboard", "пустой дашборд", "layers"),
                     ("create_card", "карточка из SQL и тип диаграммы", "list"),
                     ("add_card", "карточка на дашборд", "plus_circle")],
