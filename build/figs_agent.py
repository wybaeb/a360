# -*- coding: utf-8 -*-
"""Схемы «как устроен инструментальный агент» — рисуются кодом, без стенда.

Две фигуры: цикл агента (модель ↔ инструменты) и сборка дашборда через API BI.
Обе нужны и странице кейса, и деке, поэтому кроме встраиваемой строки SVG
модуль умеет сохранять их файлами:

    python3 build/figs_agent.py      → assets/agent_loop.svg, assets/agent_bi.svg

Палитра та же, что у страниц: акцент #20BA72, чернила #2E3641.
"""
import pathlib

ACC, DEEP, WARN, INK = "#20BA72", "#128a53", "#E4572E", "#2E3641"
ФОН, РАМКА = "rgba(32,186,114,.10)", "rgba(32,186,114,.32)"
СЕРЫЙ_ФОН, СЕРАЯ_РАМКА = "rgba(46,54,65,.05)", "rgba(46,54,65,.18)"
ШРИФТ = "system-ui,sans-serif"


def _текст(x, y, строки, размер=13.5, вес=400, цвет="rgba(46,54,65,.74)",
           якорь="start", интервал=17):
    части = []
    for i, строка in enumerate(строки):
        части.append(
            f'<text x="{x}" y="{y + i * интервал}" text-anchor="{якорь}" '
            f'font-family="{ШРИФТ}" font-size="{размер}" font-weight="{вес}" '
            f'fill="{цвет}">{строка}</text>')
    return "".join(части)


def _плашка(x, y, ш, в, заголовок, строки=(), акцент=True, моно=False):
    фон, рамка = (ФОН, РАМКА) if акцент else (СЕРЫЙ_ФОН, СЕРАЯ_РАМКА)
    шрифт_заголовка = ("ui-monospace,SFMono-Regular,Menlo,monospace" if моно
                       else ШРИФТ)
    части = [f'<rect x="{x}" y="{y}" width="{ш}" height="{в}" rx="13" '
             f'fill="{фон}" stroke="{рамка}"/>',
             f'<text x="{x + ш / 2}" y="{y + 27}" text-anchor="middle" '
             f'font-family="{шрифт_заголовка}" font-size="15" font-weight="700" '
             f'fill="{INK}">{заголовок}</text>']
    части.append(_текст(x + ш / 2, y + 46, строки, якорь="middle", размер=13,
                        интервал=16))
    return "".join(части)


def _стрелка(x1, y1, x2, y2, подпись=None, цвет=ACC, изгиб=0, сдвиг=-8):
    """Плавная стрелка: прямая при изгиб=0, дуга при изгиб≠0."""
    if изгиб:
        путь = (f'M{x1} {y1} Q{(x1 + x2) / 2} {(y1 + y2) / 2 + изгиб} {x2} {y2}')
    else:
        путь = f'M{x1} {y1} L{x2} {y2}'
    части = [f'<path d="{путь}" fill="none" stroke="{цвет}" stroke-width="2" '
             f'stroke-linecap="round" marker-end="url(#нак-{цвет.lstrip("#")})"/>']
    if подпись:
        сx, сy = (x1 + x2) / 2, (y1 + y2) / 2 + изгиб / 2 + сдвиг
        части.append(_текст(сx, сy, [подпись], размер=12.5, якорь="middle",
                            цвет="rgba(46,54,65,.62)"))
    return "".join(части)


def _наконечники(цвета=(ACC, WARN)):
    части = ["<defs>"]
    for ц in цвета:
        части.append(
            f'<marker id="нак-{ц.lstrip("#")}" viewBox="0 0 10 10" refX="9" '
            f'refY="5" markerWidth="6" markerHeight="6" orient="auto-start-reverse">'
            f'<path d="M0 0 L10 5 L0 10 z" fill="{ц}"/></marker>')
    части.append("</defs>")
    return "".join(части)


def _группа(x, y, ш, в, подпись):
    """Рамка вокруг набора инструментов с подписью в левом верхнем углу."""
    return (f'<rect x="{x}" y="{y}" width="{ш}" height="{в}" rx="16" '
            f'fill="none" stroke="rgba(46,54,65,.16)" stroke-dasharray="6 5"/>'
            f'<text x="{x + 16}" y="{y + 22}" font-family="{ШРИФТ}" '
            f'font-size="12.5" font-weight="700" letter-spacing=".08em" '
            f'fill="rgba(46,54,65,.5)">{подпись}</text>')


# ── 1. Цикл инструментального агента ────────────────────────────────────────
def цикл():
    """Вопрос → модель ⇄ инструменты → отчёт.

    Обмен «вызов / результат» показан двумя встречными стрелками в промежутке
    между моделью и инструментами: дуги поверх плашек читались хуже.
    Выход из цикла ведён понизу, чтобы не пересекать этот промежуток.
    """
    части = ['<svg viewBox="0 0 860 296" role="img" '
             'aria-label="Цикл инструментального агента: модель вызывает '
             'инструменты по очереди, пока не соберёт ответ">',
             _наконечники()]

    # Подпись в две коротких строки: «обычными словами,» в 152 px не помещается
    # и на слайде обрезается левым краем кадра.
    части.append(_плашка(0, 56, 152, 96, "Вопрос",
                         ("обычными", "словами, без SQL"), акцент=False))
    части.append(_плашка(186, 46, 164, 116, "Модель",
                         ("решает, каких", "данных не хватает,", "и что вызвать")))
    части.append(_группа(430, 10, 230, 190, "ИНСТРУМЕНТЫ"))
    части.append(_плашка(448, 34, 194, 72, "run_sql",
                         ("SELECT в базе,", "строки результата"), моно=True))
    части.append(_плашка(448, 118, 194, 72, "make_chart",
                         ("график по строкам", "запроса"), моно=True))
    части.append(_плашка(690, 202, 170, 84, "Отчёт",
                         ("таблицы, графики,", "короткий вывод"), акцент=False))

    части.append(_стрелка(154, 104, 182, 104))
    части.append(_стрелка(354, 78, 426, 78, "вызов"))
    части.append(_стрелка(426, 130, 354, 130, "результат", цвет=WARN, сдвиг=20))

    части.append(
        f'<path d="M268 164 L268 244 Q268 254 278 254 L684 254" fill="none" '
        f'stroke="{ACC}" stroke-width="2" stroke-linecap="round" '
        f'marker-end="url(#нак-{ACC.lstrip("#")})"/>')
    части.append(_текст(300, 246, ["когда данных хватает"], размер=12.5,
                        цвет="rgba(46,54,65,.62)"))

    части.append("</svg>")
    return "".join(части)


# ── 2. Агент и система дашбордов ────────────────────────────────────────────
def дашборд():
    """Те же инструменты, но создающие постоянные объекты в системе BI."""
    части = ['<svg viewBox="0 0 860 252" role="img" '
             'aria-label="Агент собирает дашборд: создать дашборд, создать '
             'карточку из SQL, положить карточку на дашборд">',
             _наконечники()]

    части.append(_плашка(0, 66, 158, 96, "Описание",
                         ("какие показатели", "и в каком виде"), акцент=False))
    части.append(_плашка(192, 66, 150, 96, "Агент",
                         ("пишет SQL", "и вызывает API")))
    части.append(_группа(384, 4, 250, 240, "ИНСТРУМЕНТЫ API"))

    инструменты = [
        (24, "create_dashboard", "пустой дашборд"),
        (96, "create_card", "карточка из SQL и тип"),
        (168, "add_card", "карточка на дашборд"),
    ]
    for y, имя, подпись in инструменты:
        части.append(_плашка(402, y, 214, 62, имя, (подпись,), моно=True))
    for y in (86, 158):
        части.append(_стрелка(509, y, 509, y + 8))

    части.append(_плашка(686, 66, 174, 96, "Дашборд в BI",
                         ("постоянный объект", "со ссылкой"), акцент=False))
    части.append(_стрелка(160, 114, 188, 114))
    части.append(_стрелка(344, 114, 398, 114))
    части.append(_стрелка(620, 114, 682, 114))

    части.append("</svg>")
    return "".join(части)


def main():
    out = pathlib.Path(__file__).resolve().parent.parent / "assets"
    out.mkdir(exist_ok=True)
    for имя, рисунок in (("agent_loop.svg", цикл()), ("agent_bi.svg", дашборд())):
        путь = out / имя
        путь.write_text('<?xml version="1.0" encoding="utf-8"?>\n' + рисунок,
                        encoding="utf-8")
        print(f"  {путь.name}: {len(рисунок) // 1024 + 1} КБ")


if __name__ == "__main__":
    main()
