# -*- coding: utf-8 -*-
"""Схемы «как устроен инструментальный агент» — рисуются кодом, без стенда.

Две фигуры: цикл агента (модель ↔ инструменты) и сборка дашборда через API BI.
Обе нужны и странице кейса, и деке, поэтому кроме встраиваемой строки SVG
модуль умеет сохранять их файлами:

    python3 build/figs_agent.py      → assets/agent_loop.svg, assets/agent_bi.svg

Вёрстка построена на сетке: единый шаг колонок и рядов, общий отступ внутри
плашек, текст выровнен по левому краю, у каждого заголовка — векторная иконка
из общего набора курса. Палитра та же, что у страниц: акцент #20BA72.
"""
import pathlib
import sys

sys.path.insert(0, "/root/work/sessions/max--76387277381017/kk_sber_a360/icons")
from icon_definitions import ICONS                             # noqa: E402

ACC, DEEP, WARN, INK = "#20BA72", "#128a53", "#E4572E", "#2E3641"
ФОН, РАМКА = "rgba(32,186,114,.10)", "rgba(32,186,114,.32)"
СЕРЫЙ_ФОН, СЕРАЯ_РАМКА = "rgba(46,54,65,.05)", "rgba(46,54,65,.18)"
ШРИФТ = "system-ui,sans-serif"
МОНО = "ui-monospace,SFMono-Regular,Menlo,monospace"

# ── Сетка ───────────────────────────────────────────────────────────────────
# Все координаты кратны шагу: колонки 236, зазор 24, внутренний отступ 18.
ШАГ_X, ЗАЗОР, ОТСТУП = 236, 24, 18
СТРОКА = 20                      # межстрочный интервал подписи
КЕГЛЬ_З, КЕГЛЬ_П = 16, 13.5      # заголовок плашки и подпись


def _иконка(имя, x, y, размер=20, цвет=DEEP, толщина=1.9):
    k = размер / 24.0
    пути = "".join(ICONS[имя]["paths"])
    return (f'<g transform="translate({x} {y}) scale({k:.4f})" fill="none" '
            f'stroke="{цвет}" stroke-width="{толщина / k:.2f}" '
            f'stroke-linecap="round" stroke-linejoin="round">{пути}</g>')


def _текст(x, y, строки, размер=КЕГЛЬ_П, вес=400, цвет="rgba(46,54,65,.76)",
           интервал=СТРОКА):
    return "".join(
        f'<text x="{x}" y="{y + i * интервал}" font-family="{ШРИФТ}" '
        f'font-size="{размер}" font-weight="{вес}" fill="{цвет}">{строка}</text>'
        for i, строка in enumerate(строки))


def _плашка(x, y, ш, в, заголовок, строки=(), икона=None, акцент=True, моно=False):
    """Плашка сетки: иконка и заголовок в одну линию, подписи под ними слева."""
    фон, рамка = (ФОН, РАМКА) if акцент else (СЕРЫЙ_ФОН, СЕРАЯ_РАМКА)
    части = [f'<rect x="{x}" y="{y}" width="{ш}" height="{в}" rx="14" '
             f'fill="{фон}" stroke="{рамка}"/>']
    тx = x + ОТСТУП
    if икона:
        части.append(_иконка(икона, x + ОТСТУП, y + ОТСТУП, 20))
        тx = x + ОТСТУП + 30
    части.append(f'<text x="{тx}" y="{y + ОТСТУП + 16}" font-family="'
                 f'{МОНО if моно else ШРИФТ}" font-size="{КЕГЛЬ_З}" '
                 f'font-weight="700" fill="{INK}">{заголовок}</text>')
    части.append(_текст(x + ОТСТУП, y + ОТСТУП + 40, строки))
    return "".join(части)


def _стрелка(x1, y1, x2, y2, подпись=None, цвет=ACC):
    части = [f'<path d="M{x1} {y1} L{x2} {y2}" fill="none" stroke="{цвет}" '
             f'stroke-width="2" stroke-linecap="round" '
             f'marker-end="url(#нак-{цвет.lstrip("#")})"/>']
    if подпись:
        части.append(
            f'<text x="{(x1 + x2) / 2}" y="{min(y1, y2) - 9}" text-anchor="middle" '
            f'font-family="{ШРИФТ}" font-size="12.5" font-weight="600" '
            f'fill="rgba(46,54,65,.6)">{подпись}</text>')
    return "".join(части)


def _наконечники(цвета=(ACC, WARN)):
    части = ["<defs>"]
    for ц in цвета:
        части.append(
            f'<marker id="нак-{ц.lstrip("#")}" viewBox="0 0 10 10" refX="9" '
            f'refY="5" markerWidth="6" markerHeight="6" orient="auto-start-reverse">'
            f'<path d="M0 0 L10 5 L0 10 z" fill="{ц}"/></marker>')
    части.append("</defs>")
    return "".join(части)


def _группа(x, y, ш, в, подпись):
    return (f'<rect x="{x}" y="{y}" width="{ш}" height="{в}" rx="16" fill="none" '
            f'stroke="rgba(46,54,65,.16)" stroke-dasharray="6 5"/>'
            f'<text x="{x + ОТСТУП}" y="{y + 22}" font-family="{ШРИФТ}" '
            f'font-size="12.5" font-weight="700" letter-spacing=".08em" '
            f'fill="rgba(46,54,65,.5)">{подпись}</text>')


# ── 1. Цикл инструментального агента ────────────────────────────────────────
# Геометрия одна на обе схемы: верхний ряд из трёх плашек шириной 236 с шагом
# 300, набор инструментов — под средней плашкой, обмен показан парой встречных
# стрелок. Все координаты кратны 2, отступы внутри плашек равны ОТСТУП.
РЯД_Y, ПЛАШКА_В = 34, 104
КОЛОНКИ = (0, 300, 600)
ГРУППА_X, ГРУППА_Ш = 270, 296


def _вертикальная(x, y1, y2, подпись, цвет=ACC, сторона="left"):
    сдвиг = -10 if сторона == "left" else 10
    якорь = "end" if сторона == "left" else "start"
    return (f'<path d="M{x} {y1} L{x} {y2}" fill="none" stroke="{цвет}" '
            f'stroke-width="2" stroke-linecap="round" '
            f'marker-end="url(#нак-{цвет.lstrip("#")})"/>'
            f'<text x="{x + сдвиг}" y="{(y1 + y2) / 2 + 4}" text-anchor="{якорь}" '
            f'font-family="{ШРИФТ}" font-size="12.5" font-weight="600" '
            f'fill="rgba(46,54,65,.6)">{подпись}</text>')


def цикл():
    """Верхний ряд «вопрос → модель → отчёт», инструменты под моделью."""
    части = ['<svg viewBox="0 0 840 402" role="img" '
             'aria-label="Цикл инструментального агента: модель вызывает '
             'инструменты по очереди, пока не соберёт ответ">',
             _наконечники()]
    x0, x1, x2 = КОЛОНКИ
    части.append(_плашка(x0, РЯД_Y, ШАГ_X, ПЛАШКА_В, "Вопрос",
                         ("обычными словами,", "без SQL"),
                         икона="chat_bubbles", акцент=False))
    части.append(_плашка(x1, РЯД_Y, ШАГ_X, ПЛАШКА_В, "Модель",
                         ("решает, каких данных", "не хватает"), икона="cpu"))
    части.append(_плашка(x2, РЯД_Y, ШАГ_X, ПЛАШКА_В, "Отчёт",
                         ("таблицы, графики,", "короткий вывод"),
                         икона="fact_check", акцент=False))
    части.append(_стрелка(x0 + ШАГ_X, РЯД_Y + 52, x1, РЯД_Y + 52))
    части.append(_стрелка(x1 + ШАГ_X, РЯД_Y + 52, x2, РЯД_Y + 52,
                          "когда данных хватает"))

    гy = РЯД_Y + ПЛАШКА_В + 62
    части.append(_группа(ГРУППА_X, гy, ГРУППА_Ш, 188, "ИНСТРУМЕНТЫ"))
    части.append(_плашка(ГРУППА_X + 12, гy + 30, ГРУППА_Ш - 24, 66, "run_sql",
                         ("SELECT в базе, строки результата",),
                         икона="database", моно=True))
    части.append(_плашка(ГРУППА_X + 12, гy + 104, ГРУППА_Ш - 24, 66, "make_chart",
                         ("график по строкам результата",),
                         икона="bar_chart", моно=True))
    части.append(_вертикальная(ГРУППА_X + 84, РЯД_Y + ПЛАШКА_В, гy, "вызов"))
    части.append(_вертикальная(ГРУППА_X + 212, гy, РЯД_Y + ПЛАШКА_В, "результат",
                               цвет=WARN, сторона="right"))
    части.append("</svg>")
    return "".join(части)


# ── 2. Агент и система дашбордов ────────────────────────────────────────────
def дашборд():
    """Та же сетка: описание → агент → дашборд, инструменты API под агентом."""
    части = ['<svg viewBox="0 0 840 476" role="img" '
             'aria-label="Агент собирает дашборд: создать дашборд, создать '
             'карточку из SQL, положить карточку на дашборд">',
             _наконечники()]
    x0, x1, x2 = КОЛОНКИ
    части.append(_плашка(x0, РЯД_Y, ШАГ_X, ПЛАШКА_В, "Описание",
                         ("какие показатели", "и в каком виде"),
                         икона="notebook", акцент=False))
    части.append(_плашка(x1, РЯД_Y, ШАГ_X, ПЛАШКА_В, "Агент",
                         ("пишет SQL", "и вызывает API"), икона="robot"))
    части.append(_плашка(x2, РЯД_Y, ШАГ_X, ПЛАШКА_В, "Дашборд в BI",
                         ("постоянный объект", "со ссылкой"),
                         икона="bar_chart", акцент=False))
    части.append(_стрелка(x0 + ШАГ_X, РЯД_Y + 52, x1, РЯД_Y + 52))
    части.append(_стрелка(x1 + ШАГ_X, РЯД_Y + 52, x2, РЯД_Y + 52))

    гy = РЯД_Y + ПЛАШКА_В + 62
    части.append(_группа(ГРУППА_X, гy, ГРУППА_Ш, 262, "ИНСТРУМЕНТЫ API"))
    инструменты = [
        (гy + 30, "create_dashboard", "пустой дашборд", "layers"),
        (гy + 104, "create_card", "карточка из SQL и тип", "list"),
        (гy + 178, "add_card", "карточка на дашборд", "plus_circle"),
    ]
    for y, имя, подпись, икона in инструменты:
        части.append(_плашка(ГРУППА_X + 12, y, ГРУППА_Ш - 24, 66, имя, (подпись,),
                             икона=икона, моно=True))
    части.append(_вертикальная(ГРУППА_X + 148, РЯД_Y + ПЛАШКА_В, гy,
                               "вызов инструментов"))
    части.append("</svg>")
    return "".join(части)


def main():
    out = pathlib.Path(__file__).resolve().parent.parent / "assets"
    out.mkdir(exist_ok=True)
    for имя, рисунок in (("agent_loop.svg", цикл()), ("agent_bi.svg", дашборд())):
        путь = out / имя
        путь.write_text('<?xml version="1.0" encoding="utf-8"?>\n' + рисунок,
                        encoding="utf-8")
        print(f"  {путь.name}: {len(рисунок) // 1024 + 1} КБ")


if __name__ == "__main__":
    main()
