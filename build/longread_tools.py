    s.append(_txt(X1, Y1 + 22, "срок обработки, дни →", 12, None, DARK, op=0.6, anchor="end"))
    s.append(_txt(X0 - 8, Y0 - 12, "число заявок", 12, None, DARK, op=0.6))
    H = [3, 7, 13, 18, 15, 9, 4, 2, 2, 4, 9, 14, 17, 12, 6, 2]
    n, hmax = len(H), max(H)
    bw = (X1 - X0 - 40) / n
