def _rows_table(headers, rows, widths=None, minw=None):
    """Таблица примеров. Ширины колонок задаются жёстко (table-layout: fixed):
    иначе колонка с кодом растягивается по самой длинной строке и вытесняет
    объяснение в узкую полоску. minw — минимальная ширина всей таблицы, ниже
    которой включается горизонтальная прокрутка контейнера .scroll."""
    ws = widths or [None] * len(headers)
    cells = []
    for h, w in zip(headers, ws):
        style = ' style="width:%s"' % w if w else ''
        cells.append('<th%s>%s</th>' % (style, h))
    head = ''.join(cells)
    body = ''.join('<tr>%s</tr>' % ''.join('<td>%s</td>' % c for c in r) for r in rows)
    style = 'table-layout:fixed' if widths else ''
    if minw:
        style += (';' if style else '') + 'min-width:%s' % minw
    attr = ' style="%s"' % style if style else ''
    return ('<div class="scroll exm"><table%s><tr>%s</tr>%s</table></div>'
            % (attr, head, body))


