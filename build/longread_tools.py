def _slide_svg(sid):
    """SVG готового слайда без внешних зависимостей: слайды со ссылками на
    внешние файлы (/illustrations/, /icons/) пропускаем.

    Если слайда с таким идентификатором в деке больше нет (деку
    перекомпоновали, слайды слили или переименовали), сборка падает: молча
    потерянная иллюстрация в материале, который уходит клиенту, дороже
    упавшей сборки."""
    try:
        with open(_DECK_PATH, encoding="utf-8") as f:
            deck = _json.load(f)
    except OSError:
        return ""
    slides = deck.get("slides", []) if isinstance(deck, dict) else deck
    if sid not in {s.get("id") for s in slides}:
        raise KeyError(
            "слайда %r нет в деке %s — иллюстрация лонгрида «Инструменты "
            "анализа» потеряна; найдите слайд под новым идентификатором"
            % (sid, _DECK_PATH))
    for s in slides:
        if s.get("id") == sid:
            svg = s.get("diagram") or ""
            if 'href="/' in svg or "/illustrations/" in svg or "/icons/" in svg:
                return ""
            svg = svg.replace(' height="100%"', '', 1)
            # Организационный слой презентации (адрес сайта материалов,
            # отсылки к номерам занятий) в тексте лишний: курс читается
            # самостоятельно, вне конкретного потока.
            for old, new in ((": wybaeb.github.io/a360", ""),
                             (" · теория и источники — лонгрид «Роль данных»", "")):
                svg = svg.replace(old, new)
            return svg
    return ""


