def _n(x, k=1):
    """Число текстом с запятой; целые — без дробной части."""
    if float(x).is_integer():
        return str(int(x))
    return f"{x:.{k}f}".replace(".", ",")


def таблица(df, k=1):
    """DataFrame → {cols, rows}: строки — списки строк (первый столбец — метка)."""
    cols = [str(c) for c in df.columns]
    rows = []
    for _, r in df.iterrows():
        row = []
        for i, v in enumerate(r):
            row.append(str(v) if i == 0 else _n(v, k))
        rows.append(row)
    return dict(cols=cols, rows=rows)


def savings():
    s = pd.read_csv(WS / "data/product/savings_monthly.csv", sep=";", decimal=",",
                    encoding="utf-8-sig")
    m = s.groupby("месяц").agg(
        новые_счета=("новые_счета", "sum"),
        закрытые_счета=("закрытые_счета", "sum"),
        активные_счета=("активные_счета_на_конец_месяца", "sum"),
        средний_остаток_тыс_руб=("средний_остаток_тыс_руб", "mean"),
        расходы_на_продвижение_тыс_руб=("расходы_на_продвижение_тыс_руб", "sum"),
        ставка_проц=("ставка_по_счёту_проц", "mean"),
        жалобы=("жалобы", "sum")).round(1).reset_index()
    return таблица(m)


def cards():
    c = pd.read_csv(WS / "data/cards/cards_issued_raw.csv", sep=";", encoding="utf-8-sig")

    def d(col):
        a = pd.to_datetime(col, format="%d.%m.%Y", errors="coerce")
        b = pd.to_datetime(col, format="%Y-%m-%d", errors="coerce")
        return a.fillna(b)
    c = c.drop_duplicates("ID карты").copy()
    c["выдача"] = d(c["Дата выдачи"])
    c["покупка"] = d(c["Дата первой покупки"])
    c["дней"] = (c["покупка"] - c["выдача"]).dt.days
    c["акт30"] = c["дней"].le(30)
    c["регион"] = c["Регион"].str.strip().str.capitalize()
    r = c.groupby("регион").agg(
        выпущено_карт=("ID карты", "count"),
        доля_активации_30_дней_проц=("акт30", "mean"),
        медиана_дней_до_первой_покупки=("дней", "median")).reset_index()
    r["доля_активации_30_дней_проц"] = (r["доля_активации_30_дней_проц"] * 100).round(1)
    r = r[["регион", "выпущено_карт", "медиана_дней_до_первой_покупки",
           "доля_активации_30_дней_проц"]]
    return таблица(r)


def ops():
    o = pd.read_csv(WS / "data/series/portfolio_operations_daily.csv", sep=";",
                    decimal=",", encoding="utf-8-sig")
    o["дата"] = pd.to_datetime(o["дата"])
    o["месяц"] = o["дата"].dt.to_period("M").astype(str)
    m = o.groupby("месяц").agg(объём_операций_млн_руб=("объём_операций_млн_руб", "sum"),
                              число_операций=("число_операций", "sum")).round(1).reset_index()
    m = m[m["месяц"] >= "2024-01"]
    return таблица(m)


def финмодель(id_):
    p = ПРЕСЕТЫ[id_]
    return dict(kind=p["kind"], delta=p["delta"], delta_unit=p["delta_unit"],
                volume=p["volume"], volume_unit=p["volume_unit"],
                price=p["price"], price_unit=p["price_unit"],
                ramp=p["ramp"], keep=p["keep"], capex=p["capex"], opex=p["opex"],
                horizon=p["horizon"], rate=p["rate"],
                assumptions=[dict(key=a[0], name=a[1], base=a[2], pess=a[3], opt=a[4])
                             for a in p["assumptions"]])


