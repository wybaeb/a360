# -*- coding: utf-8 -*-
"""Общее условие «участник действительно работал со страницей».

Отсюда условие берут обе обвязки SCORM: та, что build/build_scorm.py внедряет
в страницы пакета, и собственная обвязка тренажёра дерева метрик
(build/trainer_tree.py). Правило должно быть одно на весь курс, поэтому JS
лежит в одном месте, а не переписывается в двух.

Зачем оно нужно. Прежняя обвязка отмечала курс пройденным по одной проверке
«докрутили до низа страницы», причём вызывала её сразу при загрузке. На
лонгриде это ещё работало, а на одноэкранных тренажёрах («расчёт выборки»,
«дерево метрик») низ страницы — это и есть первый экран: условие выполнялось
в момент открытия, и LMS показывала «пройдено» тому, кто просто щёлкнул по
ссылке и закрыл вкладку. Владелец курса просил обратного: статус — по факту
работы.

Условие (a360Engagement)

  1. Настоящее событие от участника. Отсчёт вообще не начинается, пока не
     произойдёт хотя бы одно событие прокрутки, нажатия, ввода или изменения
     контрола. Синтетические события (isTrusted === false) не считаются:
     статус не должен ставить чужой скрипт.

  2. 45 секунд осмысленного времени. Секунды идут, только когда вкладка
     видима и последнее событие было не дальше 30 секунд назад. Открытая и
     забытая вкладка времени не набирает, свёрнутая — тоже.

  3. Плюс признак прохождения — свой для каждого типа страницы. Достаточно
     любого из двух, потому что страницы курса устроены по-разному, и каждая
     закрывается тем признаком, который у неё вообще есть:

       лонгрид — прокрутка до 90% высоты документа. Материал прочитан до
       конца, а не открыт на первом абзаце;

       тренажёр — 10 осмысленных действий: касания ползунков, ввод,
       переключение вкладок и наборов параметров, перенос карточек метрик.
       Прокручивать на одноэкранном тренажёре нечего («расчёт выборки»), а у
       дерева метрик прокрутка вообще внутренняя — документ не двигается
       никогда, и требовать от него глубины значило бы сделать статус
       недостижимым.

     Прокрутка при этом действием не считается: она поддерживает счётчик
     времени (участник у экрана), но не набирает те самые 10 действий. Иначе
     лонгрид «проходился» бы десятком рывков колеса на первом экране — ровно
     та подмена работы, из-за которой правило и переписывается. Серия событий
     одного жеста (перетаскивание ползунка даёт десятки input подряд) — тоже
     одно действие: между зачётами обязателен разрыв в секунду.

Порог достижим. Участник, который прошёл материал добросовестно, набирает и
45 секунд, и глубину прокрутки (или десяток действий) заведомо раньше, чем
дочитает лонгрид или подберёт параметры в калькуляторе. А вот тому, кто
пролистал лонгрид до конца за 20 секунд, статус не ставится — и это ровно то,
чего просил владелец.

Условие проверяется раз в секунду и срабатывает один раз: обработчик
onEngaged() вызывается однократно, дальше наблюдение снимается.
"""

# Функция кладётся в window: её вызывают из обвязки, которая знает, что делать
# с LMS. Сама она про LMS ничего не знает и без неё безвредна.
JS = """
(function(){
  if(window.a360Engagement) return;
  window.a360Engagement=function(onEngaged){
    var MIN_SEC=45,       /* осмысленных секунд на странице                  */
        MIN_ACTS=10,      /* действий, если прокручивать нечего              */
        DEEP=0.9,         /* доля высоты документа — «дочитано до конца»     */
        IDLE=30,          /* секунд без событий — участник отошёл            */
        SCROLLABLE=200;   /* документ выше экрана на столько — есть что крутить */
    var secs=0, acts=0, last=0, lastAct=0, deep=false, fired=false, timer=null;

    function act(e){
      if(e && e.isTrusted===false) return;       /* только настоящие события */
      var t=Date.now();
      if(t-lastAct>=1000){ acts++; lastAct=t; }  /* один жест — одно действие */
      last=t;
    }
    function onScroll(e){
      if(e && e.isTrusted===false) return;
      last=Date.now();          /* время идёт, действием прокрутка не считается */
      var d=document.documentElement,
          h=Math.max(d.scrollHeight, document.body?document.body.scrollHeight:0),
          v=window.innerHeight;
      if(h>v+SCROLLABLE && (window.scrollY+v)/h>=DEEP) deep=true;
    }
    ["pointerdown","keydown","input","change"].forEach(function(n){
      window.addEventListener(n, act, {passive:true, capture:true});
    });
    /* capture:true — прокрутка внутренних панелей тренажёров тоже событие
       участника, хотя scroll и не всплывает. */
    window.addEventListener("scroll", onScroll, {passive:true, capture:true});

    timer=setInterval(function(){
      if(document.visibilityState==="hidden") return;
      if(!last || Date.now()-last>IDLE*1000) return;
      secs++;
      if(!fired && secs>=MIN_SEC && (deep || acts>=MIN_ACTS)){
        fired=true; clearInterval(timer); onEngaged();
      }
    },1000);
  };
})();
"""
