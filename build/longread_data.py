    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..",
                        "kk_sber_a360", "decks", "step1_data_landscape.json")
    with open(path, encoding="utf-8") as f:
        slides = json.load(f)["slides"]
    svg = next(s["diagram"] for s in slides if s.get("id") == "s1b2_tree")
    # встроенное растровое изображение (иконка нижней плашки)
    svg = re.sub(r'<image[^>]*>(?:</image>)?', '', svg)
    # нижняя плашка «управленческое правило» — дублирует карточку в тексте
    svg = re.sub(r'<defs><clipPath id="clip_mt_band">.*?</clipPath></defs>', '', svg)
    svg = re.sub(r'<rect x="22" y="414"[^>]*/>', '', svg)
    svg = re.sub(r'<text x="126" y="(?:456|482|504)"[^>]*>.*?</text>', '', svg)
    # обрезаем освободившийся низ и убираем жёсткую высоту
    svg = svg.replace('viewBox="0 0 960 540"', 'viewBox="0 0 960 408"')
    svg = svg.replace(' height="100%"', '')
    # укрупняем тексты: 12 → 13.5 (названия метрик, легенда, подписи осей),
    # 11 → 12.5 (единицы измерения)
    svg = svg.replace('font-size="12"', 'font-size="13.5"')
    svg = svg.replace('font-size="11"', 'font-size="12.5"')
    return svg


