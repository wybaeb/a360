def _arrow(x0, y0, x1, y1, color=DEEP, w=2.2):
    """Линия со стрелкой на конце."""
    ang = math.atan2(y1 - y0, x1 - x0)
    L = 11
    p1 = (x1 - L * math.cos(ang - 0.42), y1 - L * math.sin(ang - 0.42))
    p2 = (x1 - L * math.cos(ang + 0.42), y1 - L * math.sin(ang + 0.42))
    return (f'<line x1="{x0}" y1="{y0}" x2="{x1}" y2="{y1}" stroke="{color}" '
            f'stroke-width="{w}" stroke-linecap="round"/>'
            f'<polygon points="{x1:.1f},{y1:.1f} {p1[0]:.1f},{p1[1]:.1f} '
            f'{p2[0]:.1f},{p2[1]:.1f}" fill="{color}"/>')


