# ── SVG-примитивы деревьев ──────────────────────────────────────────────────
ЧЕРН = "#2E3641"
ЗЕЛ = "#159A5C"


def _узел(x, y, w, строки, акцент=False, под=None):
    """Плашка-метрика: заголовок и, при необходимости, значение под ним."""
    h = 54 if под else 40
    фон = "#d9f0e5" if акцент else "#f2f7f5"
    s = [f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="10" '
         f'fill="{фон}"/>']
    if акцент:
        s.append(f'<rect x="{x}" y="{y}" width="4" height="{h}" rx="2" '
                 f'fill="{ЗЕЛ}"/>')
    s.append(f'<text x="{x + w / 2}" y="{y + 25}" text-anchor="middle" '
             f'font-size="14.5" font-weight="700" fill="{ЧЕРН}">{строки}</text>')
    if под:
        s.append(f'<text x="{x + w / 2}" y="{y + 44}" text-anchor="middle" '
                 f'font-size="12.5" fill="{ЧЕРН}" opacity="0.62">{под}</text>')
    return "".join(s)


def _связь(x1, y1, x2, y2, подпись=None):
    """Плавная стрелка вниз с подписью-формулой у середины."""
    my = (y1 + y2) / 2
    s = [f'<path d="M {x1} {y1} C {x1} {my}, {x2} {my}, {x2} {y2 - 6}" '
         f'fill="none" stroke="{ЗЕЛ}" stroke-width="1.8" '
         'marker-end="url(#arr)"/>']
    if подпись:
        якорь = "start" if x2 >= x1 else "end"
        dx = 10 if x2 >= x1 else -10
        s.append(f'<text x="{(x1 + x2) / 2 + dx}" y="{my + 4}" '
                 f'text-anchor="{якорь}" font-size="12.5" fill="{ЗЕЛ}" '
                 f'font-weight="700">{подпись}</text>')
    return "".join(s)


def _дерево(высота, тело):
    return (f'<svg viewBox="0 0 960 {высота}" '
            'xmlns="http://www.w3.org/2000/svg" role="img">'
            '<defs><marker id="arr" viewBox="0 0 10 10" refX="8" refY="5" '
            f'markerWidth="7" markerHeight="7" orient="auto-start-reverse">'
            f'<path d="M 0 0 L 10 5 L 0 10 z" fill="{ЗЕЛ}"/></marker></defs>'
            + тело + "</svg>")


def _фигура(svg, подпись):
    return (f'<figure class="tree">{svg}'
            f'<figcaption>{подпись}</figcaption></figure>')


