def make_txt():
    """TXT-копии выгрузок: веб-версия GigaChat принимает txt, но не csv."""
    d = ROOT / "data"
    for f in sorted(d.glob("*.csv")):
        with f.open(encoding="utf-8") as fh:
            rows = list(csv.reader(fh))
        (d / (f.stem + ".txt")).write_text(
            "\n".join(" | ".join(r) for r in rows), encoding="utf-8")
    print("  txt-копии выгрузок:", len(list(d.glob('*.txt'))))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--password", default=os.environ.get("A360_PASSWORD"))
    a = ap.parse_args()
    if not a.password:
        sys.exit("нужен пароль: --password '...' или A360_PASSWORD=...")

    make_txt()
    gen_js.main()          # .js-копии выгрузок + их дубли рядом с отчётами
    gen_report_shell.main()  # каркасы отчётов практики (модель пишет только расчёт)
    make_bundles.main()    # архивы «отчёт + выгрузка» под каждый разбор
    scorm = ROOT / "scorm" / "content"
    scorm.mkdir(parents=True, exist_ok=True)

    for name, title, heading, body, intro in PAGES:
        # Хлебная крошка «Материалы ▸ <страница>» — на всех страницах, кроме
        # самого хаба. Ссылка относительная, работает и в корне, и в scorm.
        crumb = None if name == "index.html" else heading
        html = theme.page(title, body if body is not None else practice.body(),
                          crumb=crumb)
        # К каждой ссылке на репозиторий — плашки «на сайте» и «скачать»:
        # в корпоративной сети github.com закрыт, github.io открыт.
        html = repolink.переписать(html)
        без_пары = repolink.сколько_без_пары(html)
        if без_пары:
            sys.exit(f"{name}: ссылки на репозиторий без копии на сайте: {без_пары}")
        (scorm / name).write_text(html, encoding="utf-8")          # открытая версия
        (ROOT / name).write_text(
            gate.wrap(html, a.password, title, heading, intro), encoding="utf-8")
        print(f"  {name:15} открытая {len(html) // 1024:>4} КБ · "
              f"зашифрованная {len(( ROOT / name).read_text(encoding='utf-8')) // 1024:>4} КБ")

    # Тренажёры дерева метрик и расчёта выборки собираются своими генераторами
    # прямо в scorm/content: это не темы сайта, а отдельные страницы со своим
    # HTML. Гейт ниже забирает их оттуда наравне с остальными внешними
    # страницами.
    trainer_tree.main()
    trainer_sample.main()

    for name, title, heading, intro in STATIC_PAGES:
        src = scorm / name
        if not src.exists():
            sys.exit(f"нет открытой копии {src} — страницу собирает отдельный "
                     f"генератор в build/, проверьте его вызов выше")
        html = src.read_text(encoding="utf-8")
        (ROOT / name).write_text(
            gate.wrap(html, a.password, title, heading, intro), encoding="utf-8")
        print(f"  {name:15} внешняя страница · зашифрована из scorm/content")

    # Ни одна страница не должна попасть в корень открытой: в корне GitHub Pages
    # лежит только шифротекст. Проверяем состав обеих версий на каждой сборке —
    # раньше страницы внешних генераторов копировали в корень мимо гейта.
    # Сверяем объединение обоих составов, а не только открытые копии: страница,
    # попавшая в корень в обход scorm/content, иначе осталась бы незамеченной —
    # ровно тот случай, ради которого проверка и заведена.
    names = sorted({p.name for p in scorm.glob("*.html")} |
                   {p.name for p in ROOT.glob("*.html")})
    missing = [n for n in names if not (ROOT / n).exists()]
    plain = [n for n in names if (ROOT / n).exists()
             and "const DATA={salt:" not in (ROOT / n).read_text(
                 encoding="utf-8", errors="replace")]
    if missing or plain:
        sys.exit(f"гейт не сошёлся: без зашифрованной версии {missing}; "
                 f"в корне открытым текстом {plain}")
    print(f"  гейт: {len(names)} страниц, все зашифрованы")

    # Ассеты, данные и готовые отчёты нужны обеим версиям: пути в HTML
    # относительные, поэтому внутри LMS всё работает так же, как на Pages.
    for sub in ("assets", "data", "demos", "reports", "downloads", "practice"):
        dst = scorm / sub
        if dst.exists():
            shutil.rmtree(dst)
        shutil.copytree(ROOT / sub, dst)
    print("  scorm/content: страницы, assets, data, reports")


if __name__ == "__main__":
    main()
