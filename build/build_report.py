# -*- coding: utf-8 -*-
"""Отчёт о проверке: теория лонгрида по источникам + промпты на GigaChat API.

Собирается из тех же модулей, которыми собраны сами материалы: цитаты — из
sources.py, результаты прогонов — из build/runs/report.json. Поэтому отчёт
нельзя «забыть обновить»: он пересобирается вместе со страницами.

Запуск: python3 build/build_report.py
"""
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from prompts import PRACTICES
from sources import (CHECKED, CHECKED_DATA, NUM, NUM_DATA, SOURCES,
                     SOURCES_DATA)

ROOT = pathlib.Path(__file__).resolve().parent.parent
RUNS = ROOT / "build" / "runs"
OUT = ROOT / "dist" / "Аналитика360_отчёт_проверки.md"

KIND_RU = {"check": "промпт 1 · выбор проверки", "code": "промпт 2 · код",
           "read": "промпт 3 · вывод", "naive": "ловушка (эталона нет)"}


def theory():
    L = ["## 1. Проверка теории лонгридов", "",
         "Проверялось каждое методическое утверждение: формулировка сверялась "
         "с источником, цитата приводится дословно на языке оригинала. Ни одно "
         "утверждение не осталось непроверенным; расхождений, требующих правки "
         "текста, не найдено — часть утверждений принята с оговоркой, и оговорка "
         "внесена в сам текст.", "",
         f"### 1.1 Лонгрид «Пять ошибок вывода» (проверено {CHECKED})", ""]
    for s in SOURCES:
        L += [f"#### {NUM[s['id']]}. {s['claim']}", "",
              f"**Источник.** {s['ref']}  ", f"<{s['url']}>", "",
              "**Цитата.**", "", f"> {s['quote']}", "",
              f"**Статус.** {s['status']}.", ""]
    L += [f"### 1.2 Лонгрид «Роль данных: категории и критерии ценности» "
          f"(проверено {CHECKED_DATA})", "",
          "Рамки самой программы (карта источников, три контекста, пять критериев "
          "ценности) — авторские, источникам не приписываются и в проверку не входят; "
          "это оговорено в тексте лонгрида.", ""]
    for s in SOURCES_DATA:
        L += [f"#### {NUM_DATA[s['id']]}. {s['claim']}", "",
              f"**Источник.** {s['ref']}  ", f"<{s['url']}>", "",
              "**Цитата.**", "", f"> {s['quote']}", "",
              f"**Статус.** {s['status']}.", ""]
    return "\n".join(L)


def prompts_report():
    f = RUNS / "report.json"
    if not f.exists():
        return "## 2. Проверка промптов\n\nПрогон не выполнялся.\n"
    res = json.loads(f.read_text(encoding="utf-8"))
    models = sorted({r["model"] for r in res})
    kinds = [k for k in ("check", "code", "read", "naive") if any(r["kind"] == k for r in res)]

    L = ["## 2. Проверка промптов практики на GigaChat API", "",
         f"Прогонов всего: **{len(res)}**. Модели: {', '.join(models)}. "
         "Температура — по умолчанию, то есть та же, что у участника в веб-версии, "
         "где регуляторов нет.", "",
         "**Как оценивался ответ.** Сначала пробовали набор регулярных выражений "
         "«есть ли в ответе такое число и такое слово» — он оказался строже самих "
         "ответов: содержательно верный разбор не проходил из-за того, что модель "
         "написала «четверть» вместо «25 %». Поэтому решение принимает судья — "
         "отдельный вызов GigaChat-2-Max, которому даются эталонный вывод и ответ "
         "и который отвечает «да/нет» на вопрос, совпадает ли главный вывод по "
         "существу. Судейство проще самого разбора, и там модель надёжна. "
         "Сырые ответы всех прогонов лежат в `build/runs/`.", ""]

    L += ["### Итог по видам промптов", "",
          "| Промпт | " + " | ".join(models) + " |",
          "|---|" + "---|" * len(models)]
    for k in kinds:
        cells = []
        for m in models:
            s = [r for r in res if r["model"] == m and r["kind"] == k]
            cells.append(f"{sum(r['ok'] for r in s)} из {len(s)}" if s else "—")
        L.append(f"| {KIND_RU[k]} | " + " | ".join(cells) + " |")
    L += ["", "«Ловушка» — наивно заданный вопрос без требования проверки. У него нет "
              "правильного ответа: он показан на странице именно для того, чтобы "
              "участник увидел, как модель подтверждает неверную гипотезу. "
              "В зачёт он не идёт.", ""]

    # Отдельная проверка кода: регулярки видят только «код пришёл», а битый
    # скрипт участник обнаружит лишь при запуске.
    import io
    import contextlib
    import check_code_syntax
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        ok_c, bad_c, empty_c = check_code_syntax.main()
    L += ["### Синтаксис выданного кода", "",
          f"Из каждого ответа промпта 2 вынут блок кода и разобран Python-ом "
          f"(`ast.parse`): **{ok_c} из {ok_c + bad_c + empty_c}** разбираются без ошибок.",
          ""]
    if bad_c:
        L += [f"Ошибок синтаксиса: {bad_c}. Все — на базовой модели GigaChat-2; типичная "
              "картина — незакрытая кавычка в имени колонки "
              "(`data['now_bn_rub'] / data['was_bn_rub]`). Это ограничение модели, "
              "промптом оно не снимается, поэтому на странице практики сказано прямо: "
              "если код не запускается, попросите переписать или возьмите модель "
              "посильнее. Вывод разбора от этого не страдает — его даёт промпт 3, "
              "который не зависит от кода.", ""]
    L += ["Детали по каждому ответу — в выводе `python3 build/check_code_syntax.py`:", "",
          "```", buf.getvalue().strip() or "(без замечаний)", "```", ""]

    L += ["### По разборам", "",
          "| Разбор | " + " | ".join(f"{m} · {KIND_RU[k].split(' · ')[-1]}"
                                     for m in models for k in ("check", "read")) + " |",
          "|---|" + "---|" * (len(models) * 2)]
    for p in PRACTICES:
        cells = []
        for m in models:
            for k in ("check", "read"):
                s = [r for r in res if r["model"] == m and r["key"] == p["key"] and r["kind"] == k]
                cells.append(f"{sum(r['ok'] for r in s)}/{len(s)}" if s else "—")
        L.append(f"| {p['num']}. {p['title']} | " + " | ".join(cells) + " |")
    L.append("")

    L += ["### Что пришлось изменить, чтобы добиться воспроизводимости", "",
          "Первая версия практики была устроена иначе: один промпт с полной выгрузкой, "
          "модель сама считает и сама делает вывод. Она не воспроизводилась ни на одной "
          "из моделей. Зафиксированные ошибки:", "",
          "- **медиана ряда из 90 значений** посчитана как 42,1 при верном значении 41,3; "
          "MAD — 7,6 при верном 2,5; в число аномальных дней попал обычный день 31.07;",
          "- **доля рынка** 142 / 279,3 названа «54 %» вместо 50,8 %, и на этой ошибке "
          "вывод перевернулся: «мы теряем долю» вместо «мы растём сильнее всех»;",
          "- **знак изменения** в табличном виде («+2,1 п.п.» в строке «Мы») прочитан "
          "как падение.", "",
          "Отсюда три изменения, которые и дали стабильность:", "",
          "1. **Роли разведены.** Промпт 1 — выбрать проверку (арифметики нет). "
          "Промпт 2 — написать код (арифметику выполняет Python). Промпт 3 — прочитать "
          "готовые числа и собрать вывод. Считать модель не просят нигде.",
          "2. **Выбор проверки сделан закрытым.** Без списка модель уходила в свою "
          "терминологию — «мультиколлинеарность», «R²», «проверка соответствия "
          "нормативу» — и два прогона подряд давали разные методы. Со списком из пяти "
          "проверок и подсказкой «когда применяется» задача стала классификацией.",
          "3. **Числа поданы фразами, а не таблицей.** В блоке результатов направление "
          "изменения названо словом («доля выросла с 50,8 % до 52,9 %, то есть "
          "на +2,1 п.п.»), а не только знаком в колонке.", "",
          "### Что осталось невыправленным", "",
          "Одна ячейка таблицы держится на 0 из 3: промпт 1 в разборе про сезонность "
          "на базовой модели GigaChat-2. Модель выбирает поиск выбросов вместо снятия "
          "сезонности и обосновывает это тем, что «аномально высокий показатель "
          "одного-двух дней способен исказить сравнение». Формулировку ситуации мы "
          "правили дважды — добавили, что кварталы соседние и внутри одного года, "
          "и что данных три полных года. Не помогло: на GigaChat-2-Max тот же самый "
          "текст даёт 3 из 3. Это разница в способностях моделей, а не дефект промпта, "
          "поэтому дальше промпт не подгонялся.", "",
          "Как это закрыто для участника: на странице практики прямо написано, "
          "в каком именно разборе базовая модель ошибается и каким встречным вопросом "
          "это лечится («а могла ли здесь быть сезонность?»), и рекомендовано выбирать "
          "GigaChat 2 Max, если он доступен. На главный промпт — третий, который "
          "и воспроизводит разбор с занятия, — это не влияет: он сошёлся с эталоном "
          "в 30 прогонах из 30 на обеих моделях.", ""]
    return "\n".join(L)


def reports_section():
    """Третья часть: HTML-обработчики выгрузок."""
    f = RUNS / "html_report.json"
    if not f.exists():
        return ""
    log = json.loads(f.read_text(encoding="utf-8"))
    L = ["## 3. HTML-отчёты по выгрузкам", "",
         "Это главный промпт практики: GigaChat собирает страницу, которая подключает "
         "лежащую рядом выгрузку, считает проверку и рисует результат — плитки с ключевыми "
         "числами, график и полосы. Считает не модель, а написанная ею страница, поэтому "
         "числа воспроизводимы.", "",
         "**Почему выгрузка в `.js`, а не в CSV.** Страницу открывают с диска, двойным "
         "кликом. По протоколу `file://` браузер запрещает `fetch` к соседнему файлу — "
         "у такого документа нет источника, и запрос считается кросс-доменным; отключать "
         "эту защиту у участника мы не можем и не должны. Обычный "
         "`<script src=\"выгрузка.js\">` под это правило не подпадает. Поэтому те же ряды "
         "продублированы в `.js`: файл объявляет `window.DATA` — массив объектов с теми же "
         "полями, что в CSV, числа уже числами. CSV и TXT остались на месте: CSV для Excel "
         "и Python, TXT для вложения в веб-версию GigaChat, которая CSV не принимает.", "",
         "**Как проверялось.** Каждая выданная страница кладётся в `reports/` рядом "
         "с выгрузкой и открывается в headless Chrome **с диска, по `file://`** — то есть "
         "ровно так, как её откроет участник. Страница должна пройти пять условий сразу:", "",
         "1. в консоли нет ошибок JavaScript;",
         "2. график нарисован: в `svg` есть фигуры и он имеет ненулевую ширину;",
         "3. в атрибутах `svg` нет `NaN`, `undefined` и `Infinity` — от них фигуры молча "
         "исчезают, не давая ошибки;",
         "4. полосы нарисованы, и их длина пропорциональна числам — вырожденный случай "
         "«все полосы одинаковой длины» не проходит;",
         "5. в тексте есть все ключевые числа разбора — те же, что на слайдах, "
         "и нигде нет `undefined` и `NaN`.", "",
         "Не прошедшая версия удаляется, промпт запрашивается заново. Публикуется "
         "только та, которая прошла всё.", "",
         "| Разбор | Ссылка | С какой попытки собралось |",
         "|---|---|---|"]
    for p_ in PRACTICES:
        v = log.get(p_["key"], {})
        mark = f"{v.get('attempt', '—')}" if v.get("ok") else "не собралось"
        L.append(f"| {p_['num']}. {p_['title']} | "
                 f"`reports/{p_['slug']}.html` | {mark} |")
    L += ["", "**Что пришлось прописать в промпте, чтобы страницы заработали.** "
              "Первые версии падали одинаково: корреляция считалась как «20,9» "
              "вместо 0,84; среднее первых 30 дней превращалось в NaN из-за пустой "
              "последней строки файла; полосы рисовались одинаковой длины независимо "
              "от значений; на просьбу «нарисуй график» модель отдавала пустой `<svg>` "
              "или координаты `NaN`. Поэтому в промпт добавлены: методика расчёта "
              "с точными определениями медианы, MAD, перцентиля и корреляции; "
              "самопроверка диапазонов (корреляция лежит в [−1; 1], доли дают 100 %); "
              "требование пропорциональности полос с готовой разметкой и CSS; "
              "и геометрия графика, заданная числами до последней координаты — "
              "`viewBox`, поля, формулы `x(i)` и `y(v)`, фильтр `Number.isFinite`, "
              "округление `.toFixed(1)`, цвета. Свободная формулировка воспроизводимости "
              "не даёт, явные формулы — дают. Итоговый текст промпта — тот, что стоит "
              "на странице практики.", "",
          "**Что осталось слабым местом.** Числа и диаграммы страницы сходятся "
          "с разбором — это проверено. А текст «Вывод» внизу отчёта пишет модель, "
          "и он устойчиво выходит мягче, чем следует из чисел: при −6,8 % год к году "
          "формулировка получается «объёмы стабильны» вместо «канал сжимается». "
          "Мы добавили в промпт прямой запрет называть снижение стабильностью "
          "и требование к направлению вывода в проверку — формулировка стала лучше, "
          "но осторожность модели этим не снимается. Поэтому на странице практики "
          "под каждой ссылкой на отчёт прямо сказано: цифрам и графикам верить можно, "
          "управленческий вывод брать из блока «что должно получиться». "
          "Дальше промпт не подгонялся — это свойство модели, а не текста запроса.", ""]
    return "\n".join(L)


def main():
    OUT.parent.mkdir(exist_ok=True)
    head = ["# Аналитика 360 · отчёт о проверке материалов", "",
            f"Даты проверки: {CHECKED} и {CHECKED_DATA}. Материалы: лонгриды "
            "предчтения «Пять ошибок вывода» и «Роль данных: категории и критерии "
            "ценности», страница самостоятельной практики в GigaChat "
            "(<https://wybaeb.github.io/a360/>).", "",
            "Отчёт состоит из трёх частей: проверка теории по первоисточникам, "
            "проверка воспроизводимости промптов на GigaChat API и проверка "
            "HTML-отчётов, которые GigaChat собрал поверх выгрузок.", "", "---", ""]
    OUT.write_text("\n".join(head) + theory() + "\n---\n\n" + prompts_report() +
                   "\n---\n\n" + reports_section(), encoding="utf-8")
    print("  ", OUT.relative_to(ROOT), OUT.stat().st_size // 1024, "КБ")


if __name__ == "__main__":
    main()
