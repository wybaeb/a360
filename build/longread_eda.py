def _svg(имя):
    """Содержимое сохранённой фигуры без XML-заголовка: вставляем прямо в HTML."""
    путь = ASSETS / имя
    if not путь.exists():
        raise FileNotFoundError(
            f"нет фигуры {путь}: соберите их заново — поднимите стенд практики "
            f"и выполните python3 build/eda_figs.py")
    текст = путь.read_text(encoding="utf-8")
    текст = re.sub(r"<\?xml[^>]*\?>", "", текст)
    текст = re.sub(r"<!DOCTYPE[^>]*>", "", текст)
    # matplotlib проставляет абсолютные размеры — снимаем их, чтобы рисунок
    # тянулся по ширине колонки на телефоне.
    текст = re.sub(r'(<svg[^>]*?)width="[^"]*"\s*height="[^"]*"', r"\1", текст, count=1)
    return текст.strip()


def _fig(имя, подпись):
    return (f'<figure class="fig">{_svg(имя)}'
            f'<figcaption>{подпись}</figcaption></figure>')


