def dq(mid):
    """Частные оценки качества данных источника: [[измерение, вес, оценка], …]."""
    vals = _DQ_PROFILES[_DQ[mid]]
    return [[n, w, v] for (n, w), v in zip(DQ_DIMS, vals)]


def dqi(mid):
    """Интегральная оценка качества данных источника, 0–100."""
    vals = _DQ_PROFILES[_DQ[mid]]
    return round(100 * sum(w * v for (_, w), v in zip(DQ_DIMS, vals)))


