# Интегральная оценка качества данных источника
# ══════════════════════════════════════════════════════════════════════════
# Шесть частных измерений и их веса — те же, что в справочнике
# (longread_metrics.html#dq-index): интегральная оценка = Σ (вес × частная
# оценка). Веса задаются один раз и меняются только через регламент, поэтому
# они вынесены сюда, в единый источник, а не в код тренажёра.
#
# Названия — дословно по ГОСТ Р 71484.2-2024 (ИСО/МЭК 5259-2:2024), раздел 6,
# там, где характеристика в стандарте есть: наполненность (6.2.2),
# аккуратность (6.2.1), согласованность (6.2.3), актуальность (6.2.5),
# прослеживаемость (6.3.5). Уникальность — наша проверка дедупликации,
# отдельной характеристикой в стандарте она не выделена; сама свёртка
# с весами — тоже методика курса, а не текст стандарта.
DQ_DIMS = [
    ("Наполненность", 0.25),     # доля записей без пропусков в обязательных полях
    ("Уникальность", 0.20),      # доля объектов без дублей после дедупликации
    ("Аккуратность", 0.20),      # доля значений, прошедших форматные и справочные проверки
    ("Согласованность", 0.15),   # доля показателей, совпадающих между системами
    ("Актуальность", 0.15),      # доля обновлений, пришедших в срок регламента
    ("Прослеживаемость", 0.05),  # доля показателей, доводимых до первичной записи
]

# Типовые профили источников. Значения учебные, но не произвольные: каждый
# профиль описывает способ получения данных, а не конкретную систему, поэтому
